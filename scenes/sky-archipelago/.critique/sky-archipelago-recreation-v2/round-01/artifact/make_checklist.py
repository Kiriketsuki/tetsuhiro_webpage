"""Writes checklist.md from build_log.txt, renders/times.json, renders/crops.json and scene_report.json."""
import json
import os
import struct

ROOT = os.path.dirname(os.path.abspath(__file__))


def png_size(path):
    with open(path, 'rb') as fh:
        head = fh.read(24)
    return struct.unpack('>II', head[16:24])


def main():
    times = json.load(open(os.path.join(ROOT, 'renders', 'times.json')))
    report = json.load(open(os.path.join(ROOT, 'scene_report.json')))
    crops = json.load(open(os.path.join(ROOT, 'renders', 'crops.json')))
    log = open(os.path.join(ROOT, 'build_log.txt'), encoding='utf-8').read().strip().splitlines()
    objs = report['objects']
    by_coll = {}
    for o in objs:
        for c in o['collections']:
            by_coll[c] = by_coll.get(c, 0) + 1
    w, h = png_size(os.path.join(ROOT, 'renders', 'final.png'))
    hw, hh = png_size(os.path.join(ROOT, 'renders', 'home_interior.png'))
    home = report.get('home', {})
    hero = [o for o in objs if o['name'].startswith('Hero_Tower.')]
    home_ext = next(o for o in objs if o['name'] == 'Home_Tower_Exterior')
    L = ['# Checklist', '',
         'Generated by `make_checklist.py` from the files of this round.', '',
         '## Times', '',
         f"- Build time, `build.py` from an empty file: {times['build_s']} s",
         f"- Render time, `renders/final.png` at {w}x{h} from `Cam_Reference`: {times['final_render_s']} s",
         f"- Render time, `renders/home_interior.png` at {hw}x{hh} from `Cam_Home`: {times['home_render_s']} s",
         f"- Compare sheet assembly: {times['compare_s']} s", '',
         '## Rebuild from an empty file', '',
         'This round opened a new empty file in Blender 5.2 (`wm.read_homefile(use_empty=True)`), ran `build.py`, '
         'and rendered `renders/final.png` and `renders/home_interior.png` straight from the rebuilt scene with '
         '`render.py`. The log below is that run. `sky_archipelago.blend` is a saved copy of the rebuilt scene.', '',
         '## Build log', '', '```', *log, '```', '',
         '## Crops in renders/compare.png', '',
         crops['layout'], '']
    for c in crops['crops']:
        x, y, cw, ch = c['render_rect_px']
        L.append(f"{c['index']}. `{c['name']}`: render pixels x {x} to {x + cw}, y {y} to {y + ch}.")
    L += ['', '## Scene facts', '',
          f"- Objects: {report['object_count']}. Materials: {len(report['materials'])}.",
          f"- Hero towers: {len(hero)}, heights {min(o['properties']['tower_height_m'] for o in hero)} m to "
          f"{max(o['properties']['tower_height_m'] for o in hero)} m.",
          f"- Home tower height: {home_ext['properties'].get('height_m')} m.",
          f"- Corner room floor-to-ceiling height: {home.get('clear_height')} m. Glass panes: {home.get('panes')}.",
          '', '## Objects per collection', '']
    for name in sorted(by_coll):
        L.append(f'- {name}: {by_coll[name]}')
    open(os.path.join(ROOT, 'checklist.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print('checklist.md written')


if __name__ == '__main__':
    main()
