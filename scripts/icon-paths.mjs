// Writes src/data/icon-paths.js: the path data of the icons that the
// interests use. Run it after a change to the icon names in interests.js.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const set = require('@iconify-json/game-icons/icons.json')
const source = readFileSync(new URL('../src/data/interests.js', import.meta.url), 'utf8')
const names = [...source.matchAll(/icon: '([a-z0-9-]+)'/g)].map((m) => m[1])

const lines = names.map((name) => {
    const body = set.icons[name]?.body
    if (!body) throw new Error(`No icon named ${name}`)
    const paths = [...body.matchAll(/ d="([^"]+)"/g)].map((m) => m[1])
    if (paths.length !== 1) throw new Error(`${name} has ${paths.length} paths`)
    return `    '${name}': '${paths[0]}',`
})

const header = `// Generated by scripts/icon-paths.mjs. Icons by Lorc, Delapouite and
// contributors, game-icons.net, CC BY 3.0. Every path sits in a 512 by 512 box.
`
writeFileSync(
    new URL('../src/data/icon-paths.js', import.meta.url),
    `${header}export const iconPaths = {\n${lines.join('\n')}\n}\n`
)
console.log(`wrote ${names.length} icons`)
